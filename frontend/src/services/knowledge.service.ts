import api from "./api";
export const summary=async()=>(await api.get("/api/knowledge/summary")).data;
export const items=async(params={})=>(await api.get("/api/knowledge/items",{params})).data;
export const item=async(id:string)=>(await api.get(`/api/knowledge/items/${id}`)).data;
export const versions=async(id:string)=>(await api.get(`/api/knowledge/items/${id}/versions`)).data;
export const relationships=async(id:string)=>(await api.get(`/api/knowledge/items/${id}/relationships`)).data;
export const itemEvidence=async(id:string)=>(await api.get(`/api/knowledge/items/${id}/evidence`)).data;
export const evidence=async()=>(await api.get("/api/knowledge/evidence")).data;
export const evidenceDetail=async(id:string)=>(await api.get(`/api/knowledge/evidence/${id}`)).data;
export const lessons=async()=>(await api.get("/api/knowledge/lessons")).data;
export const decisions=async()=>(await api.get("/api/knowledge/decisions")).data;
export const templates=async()=>(await api.get("/api/knowledge/templates")).data;
export const sources=async()=>(await api.get("/api/knowledge/sources")).data;
export const search=async(query:string)=>(await api.post("/api/knowledge/search",{query,page:1,page_size:50})).data;
